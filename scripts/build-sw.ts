import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIST_DIR = join(process.cwd(), 'dist');

function walkFiles(dir: string, relBase = ''): string[] {
  if (!existsSync(dir)) return [];
  const entries = readdirSync(dir, { withFileTypes: true });
  const out: string[] = [];
  for (const entry of entries) {
    const rel = relBase ? `${relBase}/${entry.name}` : entry.name;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...walkFiles(full, rel));
    } else if (entry.isFile()) {
      out.push(rel);
    }
  }
  return out;
}

function main(): void {
  const allFiles = walkFiles(DIST_DIR).sort();
  const precacheSet = new Set<string>(['/', '/index.html']);

  const hash = createHash('sha256');
  for (const rel of allFiles) {
    if (rel === 'sw.js' || rel === '_headers' || rel === 'sitemap.xml' || rel === 'robots.txt') {
      continue;
    }
    const urlPath = `/${rel}`;
    if (
      rel === 'index.html' ||
      rel === 'manifest.webmanifest' ||
      rel === 'guides.css' ||
      rel.startsWith('assets/') ||
      rel.startsWith('icons/')
    ) {
      precacheSet.add(urlPath);
      hash.update(rel);
      hash.update(readFileSync(join(DIST_DIR, rel)));
    }
  }

  const version = hash.digest('hex').slice(0, 10);
  const cacheName = `kilocrop-${version}`;
  const precacheUrls = [...precacheSet];

  const swSource = `/* Generated by scripts/build-sw.ts */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Navigation requests (including /?spec=... and /?n=... offline deep links)
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok && url.pathname.startsWith('/guides/')) {
            const copy = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(req, copy));
          }
          return res;
        })
        .catch(async () => {
          if (url.pathname.startsWith('/guides/')) {
            const cachedGuide = await caches.match(url.pathname);
            if (cachedGuide) return cachedGuide;
          }
          return (await caches.match('/index.html')) || (await caches.match('/'));
        }),
    );
    return;
  }

  // Static precached assets: cache-first
  event.respondWith(
    caches.match(url.pathname).then((cached) => {
      if (cached) return cached;
      return fetch(req);
    }),
  );
});
`;

  writeFileSync(join(DIST_DIR, 'sw.js'), swSource, 'utf8');
  console.log(`Generated dist/sw.js (${cacheName}, ${precacheUrls.length} precached URLs).`);
}

main();
