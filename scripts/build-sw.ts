import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIST_DIR = join(process.cwd(), 'dist');

function normalizeBasePath(raw?: string): string {
  const trimmed = (raw ?? '/').trim();
  if (!trimmed || trimmed === '/') return '/';
  const withLead = trimmed.startsWith('/') ? trimmed : `/${trimmed}`;
  return withLead.endsWith('/') ? withLead : `${withLead}/`;
}

function prefixUrl(base: string, path: string): string {
  if (base === '/') return path;
  if (path.startsWith(base)) return path;
  const rel = path.replace(/^\/+/, '');
  return rel ? `${base}${rel}` : base;
}

function rewriteManifestForBase(base: string): void {
  if (base === '/') return;
  const manifestPath = join(DIST_DIR, 'manifest.webmanifest');
  if (!existsSync(manifestPath)) return;

  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as {
    id?: string;
    scope?: string;
    start_url?: string;
    icons?: Array<{ src?: string }>;
    file_handlers?: Array<{ action?: string }>;
    share_target?: { action?: string };
  };

  if (manifest.id) manifest.id = prefixUrl(base, manifest.id);
  if (manifest.scope) manifest.scope = prefixUrl(base, manifest.scope);
  if (manifest.start_url) manifest.start_url = prefixUrl(base, manifest.start_url);
  if (Array.isArray(manifest.icons)) {
    for (const icon of manifest.icons) {
      if (icon.src) icon.src = prefixUrl(base, icon.src);
    }
  }
  if (Array.isArray(manifest.file_handlers)) {
    for (const handler of manifest.file_handlers) {
      if (handler.action) handler.action = prefixUrl(base, handler.action);
    }
  }
  if (manifest.share_target?.action) {
    manifest.share_target.action = prefixUrl(base, manifest.share_target.action);
  }

  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
}

function walkFiles(dir: string, relBase = ''): string[] {
  if (!existsSync(dir)) return [];
  const entries = readdirSync(dir, { withFileTypes: true });
  const out: string[] = [];
  for (const entry of entries) {
    const rel = relBase ? `${relBase}/${entry.name}` : entry.name;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...walkFiles(full, rel));
    } else if (entry.isFile()) {
      out.push(rel);
    }
  }
  return out;
}

function main(): void {
  const base = normalizeBasePath(process.env.BASE_PATH);
  rewriteManifestForBase(base);

  const indexHtmlPath = join(DIST_DIR, 'index.html');
  if (existsSync(indexHtmlPath)) {
    copyFileSync(indexHtmlPath, join(DIST_DIR, '404.html'));
  }
  writeFileSync(join(DIST_DIR, '.nojekyll'), '', 'utf8');

  const allFiles = walkFiles(DIST_DIR).sort();
  const precacheSet = new Set<string>([base, `${base}index.html`]);

  const hash = createHash('sha256');
  for (const rel of allFiles) {
    if (
      rel === 'sw.js' ||
      rel === '404.html' ||
      rel === '.nojekyll' ||
      rel === '_headers' ||
      rel === '_redirects' ||
      rel === 'sitemap.xml' ||
      rel === 'robots.txt'
    ) {
      continue;
    }
    const urlPath = `${base}${rel}`;
    if (
      rel === 'index.html' ||
      rel === 'manifest.webmanifest' ||
      rel === 'guides.css' ||
      rel.startsWith('assets/') ||
      rel.startsWith('icons/')
    ) {
      precacheSet.add(urlPath);
      hash.update(rel);
      hash.update(readFileSync(join(DIST_DIR, rel)));
    }
  }

  const version = hash.digest('hex').slice(0, 10);
  const cacheName = `kilocrop-${version}`;
  const precacheUrls = [...precacheSet];
  const guidesPrefix = `${base}guides/`;
  const shareImageKey = `${base}__kilocrop_shared_image__`;
  const shareRedirectUrl = `${base}?shared=1`;
  const indexUrl = `${base}index.html`;

  const swSource = `/* Generated by scripts/build-sw.ts */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};
const BASE_PATH = ${JSON.stringify(base)};
const INDEX_URL = ${JSON.stringify(indexUrl)};
const GUIDES_PREFIX = ${JSON.stringify(guidesPrefix)};
const SHARE_IMAGE_KEY = ${JSON.stringify(shareImageKey)};
const SHARE_REDIRECT_URL = ${JSON.stringify(shareRedirectUrl)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Offline PWA Web Share Target handler (?share-target=1)
  if (req.method === 'POST' && url.searchParams.has('share-target')) {
    event.respondWith(
      (async () => {
        try {
          const formData = await req.formData();
          const shared = formData.get('image');
          if (shared && typeof shared === 'object' && 'arrayBuffer' in shared) {
            const cache = await caches.open('kilocrop-share-tmp');
            const headers = new Headers({
              'Content-Type': shared.type || 'image/jpeg',
              'X-KiloCrop-Filename': encodeURIComponent(shared.name || 'shared-image.jpg'),
            });
            await cache.put(SHARE_IMAGE_KEY, new Response(shared, { headers }));
          }
        } catch {
          // Ignore malformed share payloads and redirect cleanly to app root.
        }
        return Response.redirect(SHARE_REDIRECT_URL, 303);
      })(),
    );
    return;
  }

  if (req.method !== 'GET') return;

  // Navigation requests (including ?spec=... and ?n=... offline deep links)
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok && url.pathname.startsWith(GUIDES_PREFIX)) {
            const copy = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(req, copy));
          }
          return res;
        })
        .catch(async () => {
          if (url.pathname.startsWith(GUIDES_PREFIX)) {
            const cachedGuide = await caches.match(url.pathname);
            if (cachedGuide) return cachedGuide;
          }
          return (await caches.match(INDEX_URL)) || (await caches.match(BASE_PATH));
        }),
    );
    return;
  }

  // Static precached assets: cache-first
  event.respondWith(
    caches.match(url.pathname).then((cached) => {
      if (cached) return cached;
      return fetch(req);
    }),
  );
});
`;

  writeFileSync(join(DIST_DIR, 'sw.js'), swSource, 'utf8');
  console.log(
    `Generated dist/sw.js (${cacheName}, ${precacheUrls.length} precached URLs, base=${base}).`,
  );
}

main();
